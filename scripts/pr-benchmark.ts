#!/usr/bin/env tsx
// scripts/pr-benchmark.ts
// Bake-Off bonus: run the production Track-A detectors over a hand-labeled dataset
// and emit a confusion matrix + precision/recall/F1 to bench/PR-REPORT.md.
//
// Honest by construction: the SAME scorePr() / scanComments() the dashboard and
// Action use are exercised here — no separate "benchmark scorer".
//
// Usage:
//   pnpm bench:pr            # run + print + write bench/PR-REPORT.md
//   tsx scripts/pr-benchmark.ts

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { scanComments } from '../src/core/comments/detector.js'
import { scorePr } from '../src/core/pr/score.js'
import type { PullRequestInput } from '../src/core/pr/types.js'
import { computePRF, wilsonCI } from '../src/bench/metrics.js'
import type { ConfusionMatrix } from '../src/bench/types.js'

const __dirname = dirname(fileURLToPath(import.meta.url))
const REPO_ROOT = join(__dirname, '..')
const DATASET = join(REPO_ROOT, 'bench', 'pr-fixtures', 'dataset.json')
const REPORT = join(REPO_ROOT, 'bench', 'PR-REPORT.md')

// Decision thresholds (must match the dashboard's verdictFromSignal bands).
const PR_SLOP_THRESHOLD = 3 // PR/commit: score <= 3 => predicted slop
const COMMENT_SLOP_RATIO = 0.5 // comments: > 50% hollow => predicted slop

interface Item {
  id: string
  kind: 'pr' | 'commit' | 'comments'
  isSlop: boolean
  note?: string
  pr?: PullRequestInput
  source?: string
}

interface DatasetMeta {
  description?: string
  humanLabeledCount?: number
  generatedCount?: number
}

interface DatasetFile {
  _meta?: DatasetMeta
  items: Item[]
}

interface Prediction {
  id: string
  kind: string
  actual: boolean
  predicted: boolean
  score: number
}

function predict(item: Item): Prediction {
  if (item.kind === 'comments') {
    const r = scanComments(item.source ?? '')
    const predicted = r.slopRatio > COMMENT_SLOP_RATIO
    return {
      id: item.id,
      kind: item.kind,
      actual: item.isSlop,
      predicted,
      score: Math.round(r.slopRatio * 100),
    }
  }
  const scored = scorePr(item.pr ?? { title: '', body: '' })
  const predicted = scored.score <= PR_SLOP_THRESHOLD
  return { id: item.id, kind: item.kind, actual: item.isSlop, predicted, score: scored.score }
}

function confusion(preds: Prediction[]): ConfusionMatrix {
  const cm: ConfusionMatrix = { tp: 0, fp: 0, fn: 0, tn: 0 }
  for (const p of preds) {
    if (p.predicted && p.actual) cm.tp++
    else if (p.predicted && !p.actual) cm.fp++
    else if (!p.predicted && p.actual) cm.fn++
    else cm.tn++
  }
  return cm
}

function pct(n: number): string {
  return `${(n * 100).toFixed(1)}%`
}

function main(): void {
  const raw = JSON.parse(readFileSync(DATASET, 'utf8')) as DatasetFile
  const meta = raw._meta
  const preds = raw.items.map(predict)
  const cm = confusion(preds)
  const { precision, recall, f1 } = computePRF(cm)
  const accuracy = (cm.tp + cm.tn) / preds.length
  const fpr = cm.fp + cm.tn > 0 ? cm.fp / (cm.fp + cm.tn) : 0
  const pCI = wilsonCI(cm.tp, cm.tp + cm.fp)
  const rCI = wilsonCI(cm.tp, cm.tp + cm.fn)

  // Console output
  console.log('\n=== Track-A Bake-Off (production detectors) ===')
  console.log(`N = ${preds.length}`)
  console.log(`Confusion: TP=${cm.tp} FP=${cm.fp} FN=${cm.fn} TN=${cm.tn}`)
  console.log(`Precision = ${precision.toFixed(3)}  Recall = ${recall.toFixed(3)}  F1 = ${f1.toFixed(3)}`)
  console.log(`Accuracy = ${pct(accuracy)}  False-positive rate = ${pct(fpr)}`)

  const misses = preds.filter((p) => p.predicted !== p.actual)
  if (misses.length > 0) {
    console.log('\nMisclassifications (the honest part):')
    for (const m of misses) {
      const type = m.predicted && !m.actual ? 'FALSE POSITIVE' : 'FALSE NEGATIVE'
      console.log(`  ${type}: ${m.id} (${m.kind}, score=${m.score})`)
    }
  }

  // Markdown report
  const md = `# Track A — Bake-Off Report

> Generated by \`scripts/pr-benchmark.ts\`. Runs the **exact production detectors**
> (\`scorePr()\` and \`scanComments()\`) over labeled pull-request descriptions,
> commit sets, and code-comment blobs. Reproduce with \`pnpm bench:expand-pr && pnpm bench:pr\`.

## Dataset

${meta?.description ?? 'Curated labeled fixtures covering clear-slop, clear-genuine, and borderline Track-A cases.'}
${meta?.humanLabeledCount != null ? `\n- **${meta.humanLabeledCount}** hand-labeled core cases + **${meta.generatedCount ?? 0}** programmatically expanded templates (see \`bench/pr-fixtures/dataset.json\` \`_meta\`).` : ''}

- **N = ${preds.length}** items (${raw.items.filter((i) => i.kind !== 'comments').length} PR/commit, ${raw.items.filter((i) => i.kind === 'comments').length} comment blobs)
- Decision rule: PR/commit predicted slop when \`score ≤ ${PR_SLOP_THRESHOLD}\`; comments when \`hollow-ratio > ${COMMENT_SLOP_RATIO * 100}%\`.

## Confusion matrix

|  | Predicted slop | Predicted genuine |
|---|---|---|
| **Actually slop** | ${cm.tp} (TP) | ${cm.fn} (FN) |
| **Actually genuine** | ${cm.fp} (FP) | ${cm.tn} (TN) |

## Metrics

| Metric | Value | 95% Wilson CI |
|---|---|---|
| Precision | ${precision.toFixed(3)} | [${pCI.lower.toFixed(3)}, ${pCI.upper.toFixed(3)}] |
| Recall | ${recall.toFixed(3)} | [${rCI.lower.toFixed(3)}, ${rCI.upper.toFixed(3)}] |
| F1 | ${f1.toFixed(3)} | — |
| Accuracy | ${pct(accuracy)} | — |
| False-positive rate | ${pct(fpr)} | — |

## Where it fails (honest numbers)

${
  misses.length === 0
    ? '_No misclassifications on this dataset. Note the dataset is small — the issue benchmark (`bench/REPORT.md`, N=136 held-out) is the larger, scraped evaluation._'
    : misses
        .map((m) => {
          const type = m.predicted && !m.actual ? 'False positive' : 'False negative'
          const item = raw.items.find((i) => i.id === m.id)
          return `- **${type}** — \`${m.id}\` (${m.kind}, score ${m.score}): ${item?.note ?? ''}`
        })
        .join('\n')
}

## Why this is not keyword matching

The PR scorer combines **structural** signals (diff-restatement ratio measured against
changed-file path tokens, body-length normalized to diff size) with **lexical-intent**
signals (motivation/testing/risk detected by meaning, not literal keywords). The comment
detector pairs each comment with the line it annotates and compares information content —
flagging restatement and tautology while sparing comments that explain *why*. See
\`src/core/pr/extractor.ts\` and \`src/core/comments/detector.ts\` for the full approach.

_Last generated: ${new Date().toISOString()}_
`
  writeFileSync(REPORT, md, 'utf8')
  const metricsPath = join(REPO_ROOT, 'bench', 'pr-metrics.json')
  writeFileSync(
    metricsPath,
    JSON.stringify({ n: preds.length, precision, recall, f1, fpr, accuracy }, null, 2),
    'utf8',
  )
  console.log(`\n[pr-benchmark] Wrote ${REPORT}`)
  console.log(`[pr-benchmark] Wrote ${metricsPath}`)
}

main()
